#!/usr/bin/env python3
"""Run the A+ (local-only self-insight) condition on the frozen held-out cases.

A+ differs from condition A ONLY in that each agent receives its own two
locally-generated insights about its own fault class.  Everything else —
prompt template, model, reasoning effort, parameters, repetitions, parser,
aggregation, held-out cases, local examples — is identical to the frozen
Phase B protocol.

This script does NOT modify any frozen A/B/E artifacts.
"""

