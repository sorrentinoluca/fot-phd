function observed = inspect_numeric_output(data, expected)
observed = struct( ...
    'rows', size(data, 1), ...
    'cols', size(data, 2), ...
    'time_start', NaN, ...
    'time_end', NaN, ...
    'sampling_interval', NaN, ...
    'finite_check', all(isfinite(data), 'all'), ...
    'structural_valid', false, ...
    'failure_reason', '');
if isempty(data)
    observed.failure_reason = 'numeric output is empty';
    return;
end
time = data(:, 1);
intervals = diff(time);
observed.time_start = time(1);
observed.time_end = time(end);
observed.sampling_interval = intervals(1);
checks = [ ...
    observed.rows == expected.expected_rows, ...
    observed.cols == expected.expected_columns, ...
    observed.finite_check, ...
    abs(observed.time_start - expected.start_time_h) <= 1e-10, ...
    abs(observed.time_end - expected.stop_time_h) <= 1e-10, ...
    all(intervals > 0), ...
    all(abs(intervals - expected.sampling_interval_h) <= 1e-10)];
observed.structural_valid = all(checks);
if ~observed.structural_valid
    observed.failure_reason = 'shape, finiteness, or Time-axis check failed';
end
end

function verify_written_workbook(path, headers, expectedData, expected)
assert(isfile(path), 'EXP3:WorkbookMissing', 'Workbook was not written.');
sheets = sheetnames(path);
assert(isscalar(sheets) && string(sheets(1)) == string(expected.worksheet), ...
    'EXP3:WorksheetMismatch', 'Workbook worksheet mismatch.');
observedHeaders = readcell(path, 'Sheet', char(expected.worksheet), ...
    'Range', 'A1:BB1');
assert(isequal(observedHeaders, headers), 'EXP3:HeaderMismatch', ...
    'Workbook headers mismatch.');
observedData = readmatrix(path, 'Sheet', char(expected.worksheet), ...
    'Range', 'A2:BB3002');
assert(isequal(observedData, expectedData), 'EXP3:WorkbookRoundTripMismatch', ...
    'Workbook numeric content differs after write/read round trip.');
end

function append_attempt_record(path, log, record)
if isempty(log.attempts)
    log.attempts = record;
else
    log.attempts(end + 1) = record;
end
parent = fileparts(path);
if ~isfolder(parent)
    mkdir(parent);
end
temporaryPath = [path '.tmp'];
assert(~isfile(temporaryPath), 'EXP3:AttemptLogTempExists', ...
    'Refusing to overwrite stale attempt-log temporary file.');
fid = fopen(temporaryPath, 'w');
assert(fid ~= -1, 'EXP3:AttemptLogOpen', 'Could not open attempt-log temp file.');
cleanupFile = onCleanup(@() fclose_if_open(fid));
fprintf(fid, '%s\n', jsonencode(log, 'PrettyPrint', true, ...
    'ConvertInfAndNaN', true));
fclose(fid);
clear cleanupFile;
movefile(temporaryPath, path, 'f');
end

