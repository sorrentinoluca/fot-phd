end

function digestHex = sha256_file(path)
assert(isfile(path), 'EXP3:HashInputMissing', 'Missing hash input: %s', path);
fid = fopen(path, 'rb');
assert(fid ~= -1, 'EXP3:HashInputOpen', 'Could not open hash input: %s', path);
cleanup = onCleanup(@() fclose_if_open(fid));
bytes = fread(fid, Inf, 'uint8=>uint8');
digest = java.security.MessageDigest.getInstance('SHA-256');
digest.update(bytes);
raw = typecast(digest.digest(), 'uint8');
digestHex = lower(reshape(dec2hex(raw, 2).', 1, []));
end

