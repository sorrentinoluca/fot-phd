    'structural_valid', false, ...
    'technical_failure_reason', '');
end

function observed = inspect_numeric_output(data, expected)
observed = struct( ...
    'rows', size(data, 1), ...
    'cols', size(data, 2), ...
    'time_start', NaN, ...
    'time_end', NaN, ...
    'sampling_interval', NaN, ...
    'finite_check', all(isfinite(data), 'all'), ...
    'structural_valid', false, ...
    'failure_reason', '');
if isempty(data)
    observed.failure_reason = 'numeric output is empty';
    return;
end
time = data(:, 1);
intervals = diff(time);
observed.time_start = time(1);
observed.time_end = time(end);
observed.sampling_interval = intervals(1);
observed.structural_valid = observed.rows == expected.expected_rows && ...
    observed.cols == expected.expected_columns && observed.finite_check && ...
    abs(observed.time_start - expected.start_time_h) <= 1e-10 && ...
    abs(observed.time_end - expected.stop_time_h) <= 1e-10 && ...
    all(intervals > 0) && ...
    all(abs(intervals - expected.sampling_interval_h) <= 1e-10);
if ~observed.structural_valid
    observed.failure_reason = ...
        'shape, finiteness, or Time-axis check failed';
end
end

function verify_written_workbook(path, headers, expectedData, expected)
assert(isfile(path), 'EXP3V2:WorkbookMissing', 'Workbook was not written.');
sheets = sheetnames(path);
assert(isscalar(sheets) && string(sheets(1)) == string(expected.worksheet), ...
    'EXP3V2:WorksheetMismatch', 'Workbook worksheet mismatch.');
observedHeaders = readcell(path, 'Sheet', char(expected.worksheet), ...
    'Range', 'A1:BB1');
assert(isequal(observedHeaders, headers), 'EXP3V2:HeaderMismatch', ...
    'Workbook headers mismatch.');
observedData = readmatrix(path, 'Sheet', char(expected.worksheet), ...
    'Range', 'A2:BB3002');
assert(isequal(observedData, expectedData), ...
    'EXP3V2:WorkbookRoundTripMismatch', ...
    'Workbook numeric content differs after write/read round trip.');
end

function timestamp = utc_timestamp()
value = datetime('now', 'TimeZone', 'UTC', ...
    'Format', "yyyy-MM-dd'T'HH:mm:ss.SSSXXX");
timestamp = char(string(value));
end

function digestHex = sha256_file(path)
assert(isfile(path), 'EXP3V2:HashInputMissing', 'Missing hash input: %s', path);
fid = fopen(path, 'rb');
assert(fid ~= -1, 'EXP3V2:HashInputOpen', 'Cannot open hash input: %s', path);
cleanup = onCleanup(@() fclose(fid));
bytes = fread(fid, Inf, 'uint8=>uint8');
digest = java.security.MessageDigest.getInstance('SHA-256');
digest.update(bytes);
raw = typecast(digest.digest(), 'uint8');
digestHex = lower(reshape(dec2hex(raw, 2).', 1, []));
end

function value = canonical_path(pathValue)
value = char(java.io.File(pathValue).getCanonicalPath());
end

function result = paths_overlap(left, right)
result = is_within(left, right) || is_within(right, left);
end

function result = is_within(candidate, root)
result = strcmp(candidate, root) || startsWith(candidate, [root filesep]);
end

function close_if_loaded(modelName)
if bdIsLoaded(modelName)
    close_system(modelName, 0);
end
end

function cleanup_environment(originalPath, originalDir, modelName)
close_if_loaded(modelName);
close_if_loaded('TElib');
close_if_loaded('tesys');
path(originalPath);
cd(originalDir);
end
