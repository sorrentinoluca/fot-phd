    'seed', seed, ...
    'rng_algorithm', 'twister', ...
    'started_at', startedAt, ...
    'completed_at', '', ...
    'matlab_version_full', runtime.matlab_version_full, ...
    'matlab_release', runtime.matlab_release, ...
    'matlab_build', runtime.matlab_build, ...
    'matlab_product_date', runtime.matlab_product_date, ...
    'matlab_runtime_update_date', runtime.matlab_runtime_update_date, ...
    'simulink_version', runtime.simulink_version, ...
    'simulink_release', runtime.simulink_release, ...
    'simulink_product_date', runtime.simulink_product_date, ...
    'architecture', runtime.architecture, ...
    'matlabroot', runtime.matlabroot, ...
    'simulator_commit', expected.simulator_commit, ...
    'model_name', expected.model, ...
    'simulation_mode', expected.simulation_mode, ...
    'solver', expected.solver, ...
    'sfunction_identity', expected.sfunction_identity, ...
    'sfunction_hash', expected.sfunction_source_sha256, ...
    'sfunction_mex_hash', expected.sfunction_macos_mex_sha256, ...
    'model_hash', expected.model_sha256, ...
    'initial_state_hash', expected.initial_state_sha256, ...
    'case_plan_hash', casePlanHash, ...
    'generation_script_hash', scriptHash, ...
    'output_path', outputPath, ...
    'output_size_bytes', 0, ...
